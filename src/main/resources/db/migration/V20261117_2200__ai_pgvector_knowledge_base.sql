-- Extension thuộc cả database (một bản cho app, test, design). WITH SCHEMA public để DROP SCHEMA ... CASCADE
-- của một schema app/test không kéo theo extension.
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;


-- Knowledge Base Entry (ERD #46): one text chunk of an APPROVED article with its embedding.
CREATE TABLE knowledge_base_chunks (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    expert_article_id       bigint         NOT NULL,
    chunk_index             smallint       NOT NULL,
    content                 text           NOT NULL,
    token_count             integer        NOT NULL,
    embedding_model         varchar(100)   NOT NULL,
    embedding               public.vector  NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_knowledge_base_chunks PRIMARY KEY (id),
    -- Re-embedding with another model adds rows; the same chunk exists once per model.
    CONSTRAINT uq_knowledge_base_chunks UNIQUE (expert_article_id, chunk_index, embedding_model),
    CONSTRAINT ck_knowledge_base_chunks_index CHECK (chunk_index >= 0),
    CONSTRAINT ck_knowledge_base_chunks_tokens CHECK (token_count > 0),
    -- text-embedding-3-small returns 1536 dimensions; another model must declare its own size.
    CONSTRAINT ck_knowledge_base_chunks_dims CHECK (
        embedding_model <> 'text-embedding-3-small' OR public.vector_dims(embedding) = 1536),
    CONSTRAINT fk_knowledge_base_chunks_article FOREIGN KEY (expert_article_id)
        REFERENCES expert_articles (id) ON DELETE CASCADE
);

COMMENT ON TABLE knowledge_base_chunks IS 'BR-29: the chatbot answers only from these chunks and cites expert_article_id.';

-- UC19 retrieval: cosine distance on the current model. See "Embedding storage" in the C5 header.
CREATE INDEX ix_knowledge_base_chunks_embedding_te3s
    ON knowledge_base_chunks USING hnsw ((embedding::public.vector(1536)) public.vector_cosine_ops)
    WHERE embedding_model = 'text-embedding-3-small';


-- Image Analysis (UC40, non-screen #12): vector for similar photos. With OpenAI (no image embedding
-- endpoint), the vision model writes a short description and that text is embedded with the text model.
ALTER TABLE image_analyses
    ADD COLUMN embedding_model varchar(100),
    ADD COLUMN embedding       public.vector;

ALTER TABLE image_analyses
    ADD CONSTRAINT ck_image_analyses_embedding CHECK (
        (embedding IS NULL) = (embedding_model IS NULL)
        AND (embedding_model IS DISTINCT FROM 'text-embedding-3-small' OR public.vector_dims(embedding) = 1536));

-- Similar-photo search (SCR-23, SCR-29).
CREATE INDEX ix_image_analyses_embedding_te3s
    ON image_analyses USING hnsw ((embedding::public.vector(1536)) public.vector_cosine_ops)
    WHERE embedding_model = 'text-embedding-3-small';


