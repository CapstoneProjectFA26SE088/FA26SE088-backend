-- The Photographer allows a lab to use one frame as a sample image. Revoking keeps the row
-- (revoked_at) as the history of the consent; a new consent is a new row.
CREATE TABLE scan_usage_consents (
    id                     bigint        GENERATED BY DEFAULT AS IDENTITY,
    scan_file_id           bigint        NOT NULL,
    film_lab_id            bigint        NOT NULL,
    granted_by_account_id  bigint        NOT NULL,
    granted_at             timestamptz   NOT NULL,
    revoked_at             timestamptz,
    created_at             timestamptz   NOT NULL DEFAULT now(),
    updated_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_scan_usage_consents PRIMARY KEY (id),
    CONSTRAINT ck_scan_usage_consents_revoked CHECK (revoked_at IS NULL OR revoked_at > granted_at),
    CONSTRAINT fk_scan_usage_consents_scan FOREIGN KEY (scan_file_id) REFERENCES scan_files (id),
    CONSTRAINT fk_scan_usage_consents_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_scan_usage_consents_granter FOREIGN KEY (granted_by_account_id) REFERENCES user_accounts (id)
);

-- At most one active consent per frame and lab; also serves "is this frame usable by the lab".
CREATE UNIQUE INDEX uq_scan_usage_consents_active
    ON scan_usage_consents (scan_file_id, film_lab_id)
    WHERE revoked_at IS NULL;

-- The lab confirms it deleted its copies of the scans of one order once the retention
-- period after delivery is over (LAB_SCAN_RETENTION_DAYS). One row per order.
CREATE TABLE scan_copy_deletions (
    id                       bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id         bigint        NOT NULL,
    film_lab_id              bigint        NOT NULL,
    due_at                   timestamptz   NOT NULL,
    reminder_count           smallint      NOT NULL DEFAULT 0,
    last_reminded_at         timestamptz,
    confirmed_at             timestamptz,
    confirmed_by_account_id  bigint,
    created_at               timestamptz   NOT NULL DEFAULT now(),
    updated_at               timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_scan_copy_deletions PRIMARY KEY (id),
    CONSTRAINT uq_scan_copy_deletions_order UNIQUE (service_order_id),
    CONSTRAINT ck_scan_copy_deletions_reminders CHECK (reminder_count >= 0),
    CONSTRAINT ck_scan_copy_deletions_confirmation CHECK ((confirmed_at IS NULL) = (confirmed_by_account_id IS NULL)),
    CONSTRAINT fk_scan_copy_deletions_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_scan_copy_deletions_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_scan_copy_deletions_confirmer FOREIGN KEY (confirmed_by_account_id) REFERENCES user_accounts (id)
);

-- Reminder job: deletions due and not yet confirmed.
--   WHERE confirmed_at IS NULL AND due_at < now()
CREATE INDEX ix_scan_copy_deletions_due
    ON scan_copy_deletions (due_at)
    WHERE confirmed_at IS NULL;

INSERT INTO system_parameters (param_key, param_value, value_type, description) VALUES
    ('LAB_SCAN_RETENTION_DAYS', '30', 'INTEGER', 'Days after delivery before the lab must confirm deleting its copies of the scans (BR-44)');
