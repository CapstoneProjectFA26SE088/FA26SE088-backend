ALTER TABLE film_rolls DROP CONSTRAINT fk_film_rolls_batch;
DROP INDEX ix_film_rolls_batch;
ALTER TABLE film_rolls DROP COLUMN development_batch_id;

ALTER TABLE scan_files DROP CONSTRAINT fk_scan_files_job;
ALTER TABLE scan_files DROP COLUMN scan_job_id;

DROP TABLE scan_jobs;
