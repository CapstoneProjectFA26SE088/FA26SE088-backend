-- M-01 (Review 2, KG-03): scheduling by daily lab capacity instead of developing batches.
-- =====================================================================================

-- Order Capacity Allocation: how many rolls of one order use the lab's capacity on one
-- working day, per process and format (BR-59, BR-60, BR-61). Not append-only: when a machine
-- breaks down (UC71) the allocations of the affected orders are deleted and recreated.
CREATE TABLE order_capacity_allocations (
    id                  bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id    bigint        NOT NULL,
    film_lab_id         bigint        NOT NULL,
    work_date           date          NOT NULL,
    film_process_id     bigint        NOT NULL,
    film_format_id      bigint        NOT NULL,
    service_tier        varchar(20)   NOT NULL,
    roll_count          smallint      NOT NULL,
    order_received_at   timestamptz   NOT NULL,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_order_capacity_allocations PRIMARY KEY (id),
    CONSTRAINT uq_order_capacity_allocations_line
        UNIQUE (service_order_id, work_date, film_process_id, film_format_id),
    CONSTRAINT ck_order_capacity_allocations_tier CHECK (service_tier IN ('STANDARD', 'EXPRESS')),
    -- UC20 + UC23: at most 20 declared + 5 added rolls per order.
    CONSTRAINT ck_order_capacity_allocations_rolls CHECK (roll_count BETWEEN 1 AND 25),
    CONSTRAINT fk_order_capacity_allocations_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_order_capacity_allocations_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_order_capacity_allocations_process FOREIGN KEY (film_process_id) REFERENCES film_processes (id),
    CONSTRAINT fk_order_capacity_allocations_format FOREIGN KEY (film_format_id) REFERENCES film_formats (id)
);

COMMENT ON COLUMN order_capacity_allocations.film_lab_id IS 'Copied from the order so that the machine domain queries by lab without reading service_orders.';
COMMENT ON COLUMN order_capacity_allocations.work_date IS 'Working day in Vietnam time (GMT+7).';
COMMENT ON COLUMN order_capacity_allocations.order_received_at IS 'When the lab confirmed receiving the film; FIFO order when the schedule is rebuilt (BR-61).';

-- Capacity used by one lab on one day (BR-60, BR-61 Express cap, UC71 rebuild):
--   WHERE film_lab_id = :lab AND work_date BETWEEN :from AND :to
CREATE INDEX ix_order_capacity_allocations_lab_date
    ON order_capacity_allocations (film_lab_id, work_date);

-- -------------------------------------------------------------------------------------
