-- Bảng: film_labs (+2 cột), service_packages (bỏ express_surcharge_vnd), print_price_tiers, order_print_lines (+ seed EXPRESS_COMMITMENT_WORKING_DAYS)

-- =====================================================================================
-- M-02b (Review 2, KG-04): Express surcharge as a percentage, Express commitment,
-- print price list and print lines of an order.
-- =====================================================================================

-- Express surcharge = this % of the service value (Report 4 §3.5), set once per lab.
ALTER TABLE film_labs ADD COLUMN express_surcharge_percent smallint NOT NULL DEFAULT 0;
ALTER TABLE film_labs ADD CONSTRAINT ck_film_labs_express_surcharge
    CHECK (express_surcharge_percent BETWEEN 0 AND 100);

ALTER TABLE film_labs ADD COLUMN express_commitment_working_days smallint;
ALTER TABLE film_labs ADD CONSTRAINT ck_film_labs_express_commitment
    CHECK (express_commitment_working_days IS NULL OR express_commitment_working_days BETWEEN 1 AND 2);

COMMENT ON COLUMN film_labs.express_commitment_working_days IS 'NULL = platform default EXPRESS_COMMITMENT_WORKING_DAYS; a lab may only override it with 1 or 2 working days.';

-- The per-package flat Express surcharge is replaced by the lab-level percentage above.
-- film_rolls.express_surcharge_vnd is KEPT: it is the price snapshot per roll at order creation.
ALTER TABLE service_packages DROP CONSTRAINT ck_service_packages_express;
ALTER TABLE service_packages DROP COLUMN express_surcharge_vnd;

-- Print price list of a lab: unit price per print size and quantity tier.
-- The unit price applied is the tier with the largest min_quantity <= the quantity ordered.
CREATE TABLE print_price_tiers (
    id              bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id     bigint        NOT NULL,
    print_size_id   bigint        NOT NULL,
    min_quantity    smallint      NOT NULL,
    unit_price_vnd  bigint        NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_print_price_tiers PRIMARY KEY (id),
    -- Leading column film_lab_id also serves "print price list of one lab".
    CONSTRAINT uq_print_price_tiers_tier UNIQUE (film_lab_id, print_size_id, min_quantity),
    CONSTRAINT ck_print_price_tiers_min_quantity CHECK (min_quantity >= 1),
    -- Same bound as service_packages.price_vnd (UC13).
    CONSTRAINT ck_print_price_tiers_price CHECK (unit_price_vnd BETWEEN 1 AND 50000000),
    CONSTRAINT fk_print_price_tiers_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_print_price_tiers_size FOREIGN KEY (print_size_id) REFERENCES print_sizes (id)
);

-- Print line of a Service Order. Price snapshot at order creation, like film_rolls.
CREATE TABLE order_print_lines (
    id                bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id  bigint        NOT NULL,
    film_roll_id      bigint,
    print_size_id     bigint        NOT NULL,
    quantity          smallint      NOT NULL,
    unit_price_vnd    bigint        NOT NULL,
    amount_vnd        bigint        NOT NULL,
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_order_print_lines PRIMARY KEY (id),
    CONSTRAINT ck_order_print_lines_quantity CHECK (quantity BETWEEN 1 AND 500),
    CONSTRAINT ck_order_print_lines_price CHECK (unit_price_vnd >= 0),
    CONSTRAINT ck_order_print_lines_amount CHECK (amount_vnd = quantity * unit_price_vnd),
    CONSTRAINT fk_order_print_lines_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_order_print_lines_roll FOREIGN KEY (film_roll_id) REFERENCES film_rolls (id),
    CONSTRAINT fk_order_print_lines_size FOREIGN KEY (print_size_id) REFERENCES print_sizes (id)
);

COMMENT ON COLUMN order_print_lines.film_roll_id IS 'Roll the prints are made from; NULL = the line applies to the whole order.';

-- Print lines of one order (order detail, price calculation).
CREATE INDEX ix_order_print_lines_order ON order_print_lines (service_order_id);

INSERT INTO system_parameters (param_key, param_value, value_type, description) VALUES
    ('EXPRESS_COMMITMENT_WORKING_DAYS', '2', 'INTEGER', 'Default Express commitment in working days; a lab may override with 1 or 2 (UC20, UC69)');
