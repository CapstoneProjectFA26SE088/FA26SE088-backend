-- M-02a (Review 2, KG-04): Print Size catalogue (master data).
-- The system proposes the catalogue; the Admin adds or discontinues sizes (UC53, BR-16).
-- A lab only selects sizes and sets its own prices (print_price_tiers).
-- =====================================================================================

CREATE TABLE print_sizes (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY,
    code          varchar(20)   NOT NULL,
    display_name  varchar(100)  NOT NULL,
    description   varchar(500),
    width_mm      smallint      NOT NULL,
    height_mm     smallint      NOT NULL,
    status        varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_print_sizes PRIMARY KEY (id),
    CONSTRAINT uq_print_sizes_code UNIQUE (code),
    CONSTRAINT ck_print_sizes_display_name CHECK (char_length(display_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_print_sizes_dimensions CHECK (width_mm > 0 AND height_mm > 0),
    CONSTRAINT ck_print_sizes_status CHECK (status IN ('ACTIVE', 'DISCONTINUED'))
);

